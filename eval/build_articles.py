idx = source.get()
MARKS = re.compile(r"[ً-ٰٟۖ-ۭـ﻿]")
FOLD = str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ى": "ي", "ة": "ه", "ؤ": "و", "ئ": "ي"})


def norm_words(t):
    return re.sub(r"[^ء-ي ]", " ", MARKS.sub("", t)).translate(FOLD).split()


streams = {}
for (s, n), a in sorted(idx.ayahs.items()):
    for w in norm_words(a.text):
        streams.setdefault(s, []).append((w, n))


def occurrences(ws):
    out = []
    for s, st in streams.items():
        fw = [w for w, _ in st]
        for i in range(len(fw) - len(ws) + 1):
            if fw[i:i + len(ws)] == ws:
                out.append((s, st[i][1], st[i + len(ws) - 1][1]))
    return out


def strip(t):
    return MARKS.sub("", t)


OPEN = {"﴿": "﴾", "{": "}", "«": "»", None: None}


class Q:
    """One quotation. verse words [w0,w1) of ayah (s,a); ayah_end>a means the words run on through the next verses."""

    def __init__(self, tag, s, a, w0, w1, *, a_end=None, wrong=None, plain=True, mark=None, ref=None, ref_ok=True, tags=()):
        self.tag, self.s, self.a, self.w0, self.w1, self.a_end = tag, s, a, w0, w1, a_end or a
        self.wrong, self.plain, self.mark, self.ref, self.ref_ok, self.tags = wrong or {}, plain, mark, ref, ref_ok, list(tags)

    def words(self):
        ws = []
        for n in range(self.a, self.a_end + 1):
            ws += idx.ayahs[(self.s, n)].words
        return ws

    def correct(self):
        return " ".join(self.words()[self.w0:self.w1])

    def quote(self):
        ws = self.words()[self.w0:self.w1]
        for i, new in self.wrong.items():
            ws[i] = new
        t = " ".join(ws)
        return strip(t) if self.plain else t


def render(q):
    inner = q.quote()
    if q.mark:
        return f"{q.mark}{inner}{OPEN[q.mark]}"
    return inner


def build_case(cid, category, paras, quotes, negatives, formulas):
    """paras: list of str with {tag} placeholders. Returns the case dict (offsets are found by exact substring search)."""
    by_tag = {q.tag: q for q in quotes}
    text_paras = []
    for p in paras:
        def sub(m):
            q = by_tag[m.group(1)]
            r = render(q)
            return r + (" " + q.ref if q.ref and q.ref.startswith(("[", "(")) else "")
        text_paras.append(re.sub(r"\{(\w+)\}", sub, p))
    article = "\n\n".join(text_paras)
    gold = []
    for q in quotes:
        quote = q.quote()
        assert quote in article, (cid, q.tag, quote)
        cw = norm_words(q.correct())
        locs = occurrences(cw)
        assert (q.s, q.a, q.a_end) in locs, (cid, q.tag, locs)
        wording = "wording_error" if q.wrong else "correct"
        ref_text = None
        reference = "missing"
        if q.ref:
            ref_text = q.ref.strip("[]() ")
            reference = "correct" if q.ref_ok else "incorrect"
        tags = ["marked" if q.mark else "unmarked", *q.tags]
        if q.wrong:
            tags.append("wording_error")
        if len(cw) <= 4:
            tags.append("short")
        gold.append({
            "quote": quote, "surah": q.s, "ayah_start": q.a, "ayah_end": q.a_end,
            "correct_text": strip(q.correct()), "wording": wording, "ambiguous": len(locs) > 1,
            "reference_text": ref_text, "reference": reference, "unmarked": not q.mark, "tags": sorted(set(tags)),
        })
    for n in negatives + formulas:
        assert n in article, (cid, n)
    return {"id": cid, "category": category, "article": article, "gold": gold, "negatives": negatives, "formulas": formulas}


